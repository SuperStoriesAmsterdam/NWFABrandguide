#!/usr/bin/env node
// Generate the owner-page registry + the private links list.
//
//   node scripts/vermelding/generate-registry.mjs
//
// Reads  : natuurwijn-kaart/data/venues.js
// Persists: scripts/vermelding/.tokens.secret.json   (gitignored, plaintext tokens, reused across runs)
// Writes  : natuurwijn-kaart/vermelding/registry.js   (DEPLOYABLE - only slug, index, token HASH, prefill)
//           scripts/vermelding/.links.local.csv        (gitignored, plaintext links for Peter's mailing)
//
// Tokens are stable across runs: existing slugs keep their token (so links keep working);
// only new venues get a fresh token. Delete .tokens.secret.json to rotate every token.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadVenues, buildSlugs, newToken, sha256hex, PREFILL_FIELDS } from './lib.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const VENUES_PATH = path.join(ROOT, 'natuurwijn-kaart', 'data', 'venues.js');
const REGISTRY_PATH = path.join(ROOT, 'natuurwijn-kaart', 'vermelding', 'registry.js');
const SECRET_PATH = path.join(HERE, '.tokens.secret.json');
const LINKS_PATH = path.join(HERE, '.links.local.csv');

const BASE_URL = (process.env.VERMELDING_BASE_URL
  || 'https://naturalwinefestival.nl/natuurwijn-kaart/vermelding/').replace(/\/?$/, '/');

const venues = loadVenues(VENUES_PATH);
const slugs = buildSlugs(venues);

// Load persisted tokens (slug -> token) so existing links stay valid.
let secret = {};
if (fs.existsSync(SECRET_PATH)) {
  try { secret = JSON.parse(fs.readFileSync(SECRET_PATH, 'utf8')); }
  catch { secret = {}; }
}

const registry = {};
const links = [['name', 'slug', 'token', 'url']];
let reused = 0, created = 0;

venues.forEach((v, i) => {
  const slug = slugs[i];
  if (!secret[slug]) { secret[slug] = newToken(); created++; } else { reused++; }
  const token = secret[slug];

  const d = {};
  for (const f of PREFILL_FIELDS) if (v[f] != null && v[f] !== '') d[f] = v[f];

  registry[slug] = { i, h: sha256hex(token), d };
  const url = `${BASE_URL}?v=${encodeURIComponent(slug)}&t=${encodeURIComponent(token)}`;
  links.push([v.name || '', slug, token, url]);
});

// Prune secrets for slugs that no longer exist.
for (const slug of Object.keys(secret)) if (!registry[slug]) delete secret[slug];

fs.writeFileSync(SECRET_PATH, JSON.stringify(secret, null, 0));

const banner = '// AUTO-GENERATED by scripts/vermelding/generate-registry.mjs - do not edit by hand.\n'
  + '// Contains only token HASHES (sha256) + public prefill data. Safe to deploy.\n';
fs.writeFileSync(REGISTRY_PATH, banner + 'window.VENUE_REGISTRY = ' + JSON.stringify(registry) + ';\n');

const csv = links.map((row) => row.map((c) => {
  const s = String(c);
  return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
}).join(',')).join('\n') + '\n';
fs.writeFileSync(LINKS_PATH, csv);

console.log(`venues: ${venues.length}  tokens reused: ${reused}  created: ${created}`);
console.log(`registry -> ${path.relative(ROOT, REGISTRY_PATH)}`);
console.log(`links    -> ${path.relative(ROOT, LINKS_PATH)}  (gitignored, plaintext - for the mailing)`);
console.log(`base url : ${BASE_URL}`);
